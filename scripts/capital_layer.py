"""Capital layer for the business case (evidence, not a gate).

Reads the sensitivity grid slices, takes base costs (90 percent efficiency, 0.03 USD per
kWh degradation, demand rates x1.0) for the two real tariffs, and reports installed cost,
simple payback, and NPV per battery size and strategy for the low, mid, and high ATB cases.

Usage: uv run python scripts/capital_layer.py GRID_CELLS_DIR
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd
import yaml

from edip.core.capital import installed_cost, npv, simple_payback_years, unit_costs

STRATEGIES = ["fixed_schedule", "ml_forecast", "robust_quantile", "hindsight"]
TARIFFS = ["pge_b19_secondary", "pgn_sched85_secondary"]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("cells")
    parser.add_argument("--out", default="docs/business_case_capital")
    args = parser.parse_args()
    cfg = yaml.safe_load(Path("config/capital.yaml").read_text())
    capex = pd.read_csv(cfg["source"]["extract"])
    costs = unit_costs(capex, cfg["cases"])
    grid = pd.concat([pd.read_parquet(p) for p in sorted(Path(args.cells).glob("*.parquet"))])
    base = grid[
        (grid.round_trip_efficiency == 0.9)
        & (grid.degradation_usd_per_kwh == 0.03)
        & (grid.demand_charge_multiplier == 1.0)
        & grid.tariff_id.isin(TARIFFS)
        & grid.strategy.isin(STRATEGIES)
    ]
    rows = []
    for r in base.itertuples():
        energy = r.power_kw * r.duration_hours
        for c in costs:
            cap = installed_cost(c, r.power_kw, energy)
            rows.append(
                {
                    "tariff_id": r.tariff_id,
                    "strategy": r.strategy,
                    "power_fraction": r.power_fraction,
                    "power_kw": r.power_kw,
                    "energy_kwh": energy,
                    "cost_case": c.case,
                    "installed_cost_usd": cap,
                    "annual_net_benefit_usd": r.net_benefit_usd,
                    "simple_payback_years": simple_payback_years(cap, r.net_benefit_usd),
                    "npv_usd": npv(cap, r.net_benefit_usd, cfg["life_years"], cfg["discount_rate"]),
                }
            )
    table = pd.DataFrame(rows)
    payload = {
        "label": cfg["label"],
        "result_label": str(grid.result_label.iloc[0]),
        "life_years": cfg["life_years"],
        "discount_rate": cfg["discount_rate"],
        "dollar_year_capex": cfg["source"]["dollar_year"],
        "unit_costs": [c.model_dump() for c in costs],
        "rows": table.astype(object).where(table.notna(), None).to_dict("records"),
    }
    Path(args.out + ".json").write_text(json.dumps(payload, indent=2) + "\n")
    lines = [
        "# Capital layer (evidence, not a gate)",
        "",
        "Generated by `scripts/capital_layer.py` from the sensitivity grid "
        f"({payload['result_label']}). Installed cost from NREL/NLR 2025 ATB commercial "
        f"battery storage, cost year 2026, {cfg['source']['dollar_year']} dollars (ASSUMED "
        f"cases); life {cfg['life_years']} years and "
        f"discount rate {cfg['discount_rate']:.0%} are ASSUMED. Base costs: 90% efficiency, "
        "0.03 USD/kWh degradation, demand rates x1.0. Annual net benefit is against no battery, "
        "before tax. Fixed O&M, replacement, and incentives are excluded.",
        "",
        "| Case | ATB scenario | USD per kWh | USD per kW |",
        "|---|---|---|---|",
    ]
    lines += [
        f"| {c.case} | {c.atb_scenario} | {c.usd_per_kwh:,.1f} | {c.usd_per_kw:,.1f} |"
        for c in costs
    ]
    for tariff in TARIFFS:
        lines += [
            "",
            f"## {tariff}",
            "",
            "| Battery | Strategy | Annual net benefit | Installed cost low / mid / high "
            "| Payback years (mid) | NPV low / mid / high |",
            "|---|---|---|---|---|---|",
        ]
        sub = table[table.tariff_id == tariff]
        for (pf, kw, kwh, strat), g in sub.groupby(
            ["power_fraction", "power_kw", "energy_kwh", "strategy"], sort=True
        ):
            g = g.set_index("cost_case")
            pb = g.loc["mid", "simple_payback_years"]
            lines.append(
                f"| {pf:.0%} / {kwh / kw:.0f} h ({kw:,.0f} kW, {kwh:,.0f} kWh) | {strat} | "
                f"{g.loc['mid', 'annual_net_benefit_usd']:,.0f} | "
                + " / ".join(
                    f"{g.loc[c, 'installed_cost_usd']:,.0f}" for c in ("low", "mid", "high")
                )
                + f" | {'never' if pd.isna(pb) else f'{pb:,.1f}'} | "
                + " / ".join(f"{g.loc[c, 'npv_usd']:,.0f}" for c in ("low", "mid", "high"))
                + " |"
            )
    Path(args.out + ".md").write_text("\n".join(lines) + "\n")
    print(f"{len(table)} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
